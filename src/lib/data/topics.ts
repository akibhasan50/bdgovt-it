export function getTopic(slug: string) {
  return topics.find((t) => t.slug === slug);
}

export function getRelatedTopics(slug: string) {
  const topic = getTopic(slug);
  if (!topic) return [];
  return topic.related
    .map((s) => getTopic(s))
    .filter((t): t is Topic => Boolean(t));
}
